/*
 * Formatted by prettier on the way out.
 *
 * The repo checks every file with prettier, so a generator that emits markdown
 * prettier would rewrite gives you two commands that disagree about the same
 * file forever — `yarn docs` writes it, `yarn lint` rejects it. Running its
 * output through the same formatter the repo uses settles that at the source.
 */
const config = (await prettier.resolveConfig(join(ROOT, 'docs/wiki/README.md'))) ?? {};
const format = (text) => prettier.format(text, { ...config, parser: 'markdown' });

const built = new Map();
for (const page of PAGES) built.set(page.file, await format(page.build()));
built.set('README.md', await format(indexPage(PAGES)));

if (CHECK) {
	const stale = [];
	for (const [file, content] of built) {
		const path = join(OUT, file);
		if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(file);
	}
	// Something committed that the generator no longer produces is drift too.
	const extra = existsSync(OUT)
		? readdirSync(OUT).filter((f) => f.endsWith('.md') && !built.has(f))
		: [];

	if (stale.length || extra.length) {
		console.error('The wiki is out of date. Run `yarn docs` and commit the result.\n');
		for (const f of stale) console.error(`  stale:   docs/wiki/${f}`);
		for (const f of extra) console.error(`  orphan:  docs/wiki/${f}`);
		process.exit(1);
	}
	console.log(`docs: ${built.size} pages up to date`);
} else {
	rmSync(OUT, { recursive: true, force: true });
	mkdirSync(OUT, { recursive: true });
	for (const [file, content] of built) writeFileSync(join(OUT, file), content);
	console.log(`docs: wrote ${built.size} pages to docs/wiki/`);
}
